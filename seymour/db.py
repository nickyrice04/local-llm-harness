"""The data layer: every table Seymour has, in one readable file.

The guide's Chapter 9 started with two tables (sessions, messages) and warned
against designing tables for features that don't exist yet. Every table below
exists because a shipped feature writes to it:

    sessions / messages  — chat history            (routes/chat.py)
    memories             — the RAG memory store     (memory/)
    agent_tasks          — the primary agent's jobs (agent/)
    agent_steps          — the agent's step journal (agent/loop.py)
    app_state            — tiny key/value: onboarding flag, active model, …
"""

# datetime for timestamps; timezone so they are never naive (see utcnow below).
from datetime import datetime, timezone

# The SQLAlchemy pieces we use. Text = unbounded string column type;
# ForeignKey = a column that references another table's primary key.
from sqlalchemy import ForeignKey, Text, create_engine, event
from sqlalchemy.orm import (
    DeclarativeBase,   # base class that registers our models
    Mapped,            # type annotation marker for mapped columns
    mapped_column,     # column definition helper
    relationship,      # ORM-level link between two tables
    sessionmaker,      # factory for database sessions
)

# All paths and knobs come from config — nothing here is hard-coded.
from seymour.config import settings


def utcnow() -> datetime:
    """Timezone-aware UTC. datetime.utcnow() is deprecated and, worse, returns
    a NAIVE datetime — one with no timezone attached — which silently compares
    wrongly against aware ones. Always store UTC; convert for display only."""
    return datetime.now(timezone.utc)


class Base(DeclarativeBase):
    """SQLAlchemy's registry. Every model class inherits from this, which is
    how create_all() below knows what tables to make."""


# --------------------------------------------------------------------------- #
#  Chat                                                                       #
# --------------------------------------------------------------------------- #

class ChatSession(Base):
    """One conversation in the foreground chat."""

    __tablename__ = "sessions"

    # A UUID string, generated by the route when the conversation starts.
    id: Mapped[str] = mapped_column(primary_key=True)
    # Shown in the sidebar. Starts as the first message's opening words.
    title: Mapped[str] = mapped_column(default="New conversation")
    # What KIND of chat this started as: "chat" | "agent" | "research".
    # The OOP framing: every conversation is a chat; some are special
    # kinds of chat. The sidebar renders the matching symbol.
    kind: Mapped[str] = mapped_column(default="chat")
    # The job this chat most recently spawned (a discrete task's or a
    # research run's id) — how the sidebar knows the chat is LIVE in a
    # slot right now (labels carry the job id's first 8 chars).
    job_id: Mapped[str] = mapped_column(default="")
    created_at: Mapped[datetime] = mapped_column(default=utcnow)
    # onupdate=utcnow keeps this fresh automatically on every write.
    updated_at: Mapped[datetime] = mapped_column(default=utcnow, onupdate=utcnow)

    # The ORM half of the foreign key on Message:
    #   cascade="all, delete-orphan" → deleting a session deletes its messages
    #   order_by                     → messages always come back in order
    messages: Mapped[list["Message"]] = relationship(
        back_populates="session",
        cascade="all, delete-orphan",
        order_by="Message.created_at",
    )


class Message(Base):
    """One turn in a conversation."""

    __tablename__ = "messages"

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    # index=True because every message lookup filters by session_id. Without
    # it SQLite scans the whole table; with it, this stays fast at 10k rows.
    session_id: Mapped[str] = mapped_column(ForeignKey("sessions.id"), index=True)
    # Who spoke: "user" | "assistant" | "system".
    role: Mapped[str]
    # Text, not String: no length cap on a model's reply.
    content: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(default=utcnow)

    session: Mapped[ChatSession] = relationship(back_populates="messages")


# --------------------------------------------------------------------------- #
#  Memory (the RAG store)                                                     #
# --------------------------------------------------------------------------- #

class MemoryEntry(Base):
    """One remembered fact, reviewable and deletable by the user.

    Retrieval works by embedding: `embedding` holds the entry's vector as a
    JSON array of floats, and memory/rag.py compares it against the query's
    vector by cosine similarity. Storing the vector next to the text keeps
    the whole memory system in one table you can inspect with sqlite3.
    """

    __tablename__ = "memories"

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    # The remembered text itself — short, one fact per row.
    content: Mapped[str] = mapped_column(Text)
    # A coarse category shown in the UI: "fact" | "preference" | "note".
    kind: Mapped[str] = mapped_column(default="fact")
    # Where it came from: "user" (typed in), "agent" (saved by a tool call),
    # or "chat" (distilled from a conversation). Provenance builds trust.
    source: Mapped[str] = mapped_column(default="user")
    # The embedding vector as JSON text, e.g. "[0.12, -0.4, …]".
    # Text rather than a binary blob so `sqlite3` shows something readable.
    embedding: Mapped[str] = mapped_column(Text, default="[]")
    # Which embedder produced the vector ("llama" or "hashing"). Vectors from
    # different embedders are NOT comparable, so retrieval filters on this.
    embedder: Mapped[str] = mapped_column(default="hashing")
    # Pinned memories outrank retrieval: CORE pins (identity/contact) ride
    # in every chat; other pins are retrieved-before-ordinary. The Odysseus
    # lesson: importance is expressed structurally (pinned + category +
    # uses), not as a made-up numeric score.
    pinned: Mapped[bool] = mapped_column(default=False)
    # How many times this memory was actually INJECTED into a chat context
    # (retrieval alone doesn't count) — visible in the UI as "12×".
    uses: Mapped[int] = mapped_column(default=0)
    created_at: Mapped[datetime] = mapped_column(default=utcnow)


# --------------------------------------------------------------------------- #
#  The primary agent                                                          #
# --------------------------------------------------------------------------- #

class AgentTask(Base):
    """One job given to the primary background agent.

    The status field is the task's lifecycle state machine:

        queued → running → done | failed | cancelled
                    ↕
                 paused  (user asked, battery critical, …)
                    ↕
                 blocked (waiting for the user to approve an action)
    """

    __tablename__ = "agent_tasks"

    id: Mapped[str] = mapped_column(primary_key=True)   # a UUID string
    # What the user asked for, verbatim. The loop re-reads this every step.
    goal: Mapped[str] = mapped_column(Text)
    # Which kind of agent work this is:
    #   "primary" — the continuous background seat (Tier 3, one at a time,
    #               queued behind each other, often open-ended)
    #   "task"    — a discrete foreground job started from chat (Tier 2,
    #               several may run at once, expected to finish)
    kind: Mapped[str] = mapped_column(default="primary", index=True)
    # The lifecycle state — see the docstring diagram above.
    status: Mapped[str] = mapped_column(default="queued", index=True)
    # The chat this task was started from, if any — the organizer tabs
    # link back to it ("every task is a special kind of chat").
    session_id: Mapped[str] = mapped_column(default="")
    # The agent's own running notes: what it has learned/done so far. This is
    # the checkpoint that survives restarts — the loop rebuilds its prompt
    # from goal + notes + recent steps, so no context is lost when Seymour
    # (or the laptop lid) closes.
    notes: Mapped[str] = mapped_column(Text, default="")
    # Filled in when the task finishes: the agent's final report.
    result: Mapped[str] = mapped_column(Text, default="")
    created_at: Mapped[datetime] = mapped_column(default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(default=utcnow, onupdate=utcnow)

    # The step journal, oldest first (see AgentStep).
    steps: Mapped[list["AgentStep"]] = relationship(
        back_populates="task",
        cascade="all, delete-orphan",
        order_by="AgentStep.id",
    )


class AgentStep(Base):
    """One entry in a task's journal — the agent's visible work log.

    Everything the agent does lands here, which is what makes the agent
    auditable: the UI renders this journal live, and after a restart the
    loop replays the recent tail to rebuild its context.
    """

    __tablename__ = "agent_steps"

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    task_id: Mapped[str] = mapped_column(ForeignKey("agent_tasks.id"), index=True)
    # What kind of entry: "thought" | "tool_call" | "tool_result" |
    # "approval_request" | "approval_response" | "status" | "error".
    kind: Mapped[str]
    # The entry body. For tool calls/results this is JSON text; for thoughts
    # it is prose. Kept as Text so sqlite3 shows it directly.
    content: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(default=utcnow)

    task: Mapped[AgentTask] = relationship(back_populates="steps")


# --------------------------------------------------------------------------- #
#  Runs and their event log (the harness rebuild's substrate)                 #
# --------------------------------------------------------------------------- #

class Run(Base):
    """One execution spawned by one user message (the rebuild's central
    primitive): policy is resolved PER MESSAGE at send time and recorded
    here — never latched onto the conversation.

    A run's whole story lives in its RunEvents; this row is the index
    card — preset, state, and summary stats for lists and filters.
    """

    __tablename__ = "runs"

    id: Mapped[str] = mapped_column(primary_key=True)     # uuid4 string
    session_id: Mapped[str] = mapped_column(index=True)   # its conversation
    # Which policy preset resolved for this message: "chat" | "deep_research".
    preset: Mapped[str] = mapped_column(default="chat")
    # running | done | failed | cancelled  (approval states arrive with
    # the write-gating increment).
    status: Mapped[str] = mapped_column(default="running")
    # Summary stats as JSON text (tool_calls, tokens, seconds, outcome
    # details) — filled once at completion; the per-step truth is events.
    stats: Mapped[str] = mapped_column(Text, default="")
    created_at: Mapped[datetime] = mapped_column(default=utcnow)
    finished_at: Mapped[datetime | None] = mapped_column(default=None)

    events: Mapped[list["RunEvent"]] = relationship(
        back_populates="run", cascade="all, delete-orphan",
        order_by="RunEvent.seq")


class RunEvent(Base):
    """One typed entry in a run's append-only event log.

    THE source of truth for traceability: everything the run did — each
    model call, each tool call with its payload and result, each policy
    decision — appends here as it happens, and the trace UI is a straight
    read of this table (never a parallel bookkeeping path). Types:
    "run_start" | "model_call" | "model_result" | "tool_call" |
    "tool_result" | "repair" | "note" | "run_end".
    """

    __tablename__ = "run_events"

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    run_id: Mapped[str] = mapped_column(ForeignKey("runs.id"), index=True)
    seq: Mapped[int]                          # order within the run
    type: Mapped[str]
    # The payload as JSON text. Bounded at write time (BIG tool results
    # are excerpted with their true length noted) — the log must stay
    # cheap to read forever.
    data: Mapped[str] = mapped_column(Text, default="")
    created_at: Mapped[datetime] = mapped_column(default=utcnow)

    run: Mapped[Run] = relationship(back_populates="events")


