class Upload(Base):
    """One file the user attached in chat — document or image.

    The bytes live on disk under uploads/; this row is the ledger: what it
    was called, what type it is, and (for documents) the extracted text so
    a re-attach never re-parses. Images additionally join the gallery.
    """

    __tablename__ = "uploads"

    id: Mapped[str] = mapped_column(primary_key=True)      # a UUID string
    # The stored filename (uuid + original extension), inside uploads/.
    filename: Mapped[str] = mapped_column(unique=True)
    # The user's original name — what the UI shows on the chip.
    original_name: Mapped[str] = mapped_column(default="")
    # "image" | "document" — decides how chat injects it.
    kind: Mapped[str] = mapped_column(default="document")
    # The declared/derived MIME type (image/png, application/pdf, …).
    mime: Mapped[str] = mapped_column(default="")
    # For documents: the extracted text (bounded), ready for guard-wrapping.
    text: Mapped[str] = mapped_column(Text, default="")
    size_bytes: Mapped[int] = mapped_column(default=0)
    created_at: Mapped[datetime] = mapped_column(default=utcnow)


class GalleryImage(Base):
    """One image in the gallery — every image that passes through Seymour.

    A compact adaptation of Odysseus's gallery schema (see
    ACKNOWLEDGMENTS.md): enough to browse, name, favorite and delete, and
    nothing speculative.
    """

    __tablename__ = "gallery_images"

    id: Mapped[str] = mapped_column(primary_key=True)      # a UUID string
    # The stored filename inside the gallery directory.
    filename: Mapped[str] = mapped_column(unique=True)
    # The display name (defaults to the original upload name).
    name: Mapped[str] = mapped_column(default="")
    # Where it came from: "chat-upload" for now (generation may come later).
    source: Mapped[str] = mapped_column(default="chat-upload")
    # The chat session it arrived in, if any (loose link, no FK cascade).
    session_id: Mapped[str] = mapped_column(default="")
    favorite: Mapped[bool] = mapped_column(default=False)
    created_at: Mapped[datetime] = mapped_column(default=utcnow)


