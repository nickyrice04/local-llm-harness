class AppState(Base):
    """A tiny key/value table for one-off application state.

    Used for: "onboarding_done" (first-launch tour), "active_model" (which
    .gguf the engine should load), and similar single values. A dedicated
    table per flag would be ceremony; a config file would be a second source
    of truth next to the database. One k/v table is the honest size.
    """

    __tablename__ = "app_state"

    key: Mapped[str] = mapped_column(primary_key=True)
    value: Mapped[str] = mapped_column(Text)


# --------------------------------------------------------------------------- #
#  Engine and session factory                                                 #
# --------------------------------------------------------------------------- #

# check_same_thread=False: SQLite defaults to refusing use from a thread other
# than the one that opened it. Our handlers are async (event-loop thread) but
# hot paths push DB work into worker threads via asyncio.to_thread, so
# connections legitimately move between threads. Safe here because we open
# a fresh session per request and never share one across concurrent work.
engine = create_engine(
    f"sqlite:///{settings.db_path}",
    connect_args={"check_same_thread": False},
)


@event.listens_for(engine, "connect")
def _tune_sqlite(dbapi_connection, _record) -> None:
    """Per-connection SQLite pragmas — the three that matter here.

    - WAL journaling: writers stop blocking readers, and commits become
      cheap appends instead of full-database fsync dances. This is what
      keeps a journal write from freezing every live token stream (all
      our async handlers share one event-loop thread).
    - synchronous=NORMAL: the safe pairing with WAL — durable against
      app crashes, losing at most the final commit in an OS-level crash.
      A chat app on a laptop takes that trade happily.
    - foreign_keys=ON: SQLite ships with FK enforcement OFF; without this
      a journal row for a deleted (or never-existing) task id inserts
      silently instead of failing loudly.
    """
    cursor = dbapi_connection.cursor()
    cursor.execute("PRAGMA journal_mode=WAL")
    cursor.execute("PRAGMA synchronous=NORMAL")
    cursor.execute("PRAGMA foreign_keys=ON")
    cursor.close()

# expire_on_commit=False: after commit(), objects keep their loaded values
# instead of being expired and re-fetched — which matters because we often
# read attributes (like a new session's id) after the session block closes.
SessionLocal = sessionmaker(bind=engine, expire_on_commit=False)


# Columns added to EXISTING tables after v1 shipped. create_all() only
# creates missing TABLES, so these few need explicit ALTERs on databases
# created before the column existed. (table, column, DDL type+default).
_LATE_COLUMNS: list[tuple[str, str, str]] = [
    ("agent_tasks", "kind", "VARCHAR DEFAULT 'primary'"),
    ("agent_tasks", "session_id", "VARCHAR DEFAULT ''"),
    ("memories", "pinned", "BOOLEAN DEFAULT 0"),
    ("memories", "uses", "INTEGER DEFAULT 0"),
    ("sessions", "kind", "VARCHAR DEFAULT 'chat'"),
    ("sessions", "job_id", "VARCHAR DEFAULT ''"),
]


def init_db() -> None:
    """Create tables if they don't exist, and add late columns. Idempotent
    — safe on every startup.

    Not a real migration system — just create_all() plus a short list of
    ALTER TABLE ADD COLUMN statements for columns that arrived after v1
    (SQLite adds columns in place, cheaply). Fine for one developer on
    one laptop; anything structural still means migrating by hand.
    """
    Base.metadata.create_all(engine)
    with engine.connect() as connection:
        for table, column, ddl in _LATE_COLUMNS:
            # Ask SQLite what columns the live table actually has…
            have = {row[1] for row in
                    connection.exec_driver_sql(f"PRAGMA table_info({table})")}
            # …and add the column only if a pre-upgrade database lacks it.
            if have and column not in have:
                connection.exec_driver_sql(
                    f"ALTER TABLE {table} ADD COLUMN {column} {ddl}")
        connection.commit()


# ---- App-state helpers (the whole API the k/v table needs) ----------------- #

def get_state(key: str, default: str | None = None) -> str | None:
    """Read one value from app_state, or `default` if the key is absent."""
    with SessionLocal() as db:
        row = db.get(AppState, key)
        return row.value if row else default


def set_state(key: str, value: str) -> None:
    """Write one value to app_state, inserting or overwriting as needed."""
    with SessionLocal() as db:
        # merge() = insert-or-update by primary key, in one call.
        db.merge(AppState(key=key, value=value))
        db.commit()
