/** icons.ts — the pixel icon set, drawn in code.
 *
 * Every icon is a 16×16 grid of filled cells, authored as rows of text
 * (# = filled, . = empty) exactly like classic sprite sheets — readable,
 * diffable, and rendered crisp at any size via SVG rects with
 * shape-rendering: crispEdges. They inherit currentColor, so the theme
 * recolors them for free.
 */

/** Turn a 16-row text grid into an inline SVG element. */
function pixelIcon(rows: string[]): SVGSVGElement {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 16 16");
  svg.setAttribute("class", "picon");
  svg.setAttribute("aria-hidden", "true");
  // One <rect> per filled cell; crispEdges keeps them square at any scale.
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== "#") continue;
      const rect = document.createElementNS("http://www.w3.org/2000/svg", "rect");
      rect.setAttribute("x", String(x));
      rect.setAttribute("y", String(y));
      rect.setAttribute("width", "1");
      rect.setAttribute("height", "1");
      rect.setAttribute("fill", "currentColor");
      rect.setAttribute("shape-rendering", "crispEdges");
      svg.append(rect);
    }
  });
  return svg;
}

